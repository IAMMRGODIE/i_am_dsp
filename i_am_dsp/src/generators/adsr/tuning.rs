/// A tuning system that converts MIDI note numbers to frequencies in Hz
pub trait Tuning {
	/// Returns frequency in Hz for given MIDI note number
	///
	/// Note: We allow note number to be float to allow for microtonal tuning
	fn get_frequency(&self, note: f32) -> f32;
}

/// The 12-tone equal temperament tuning system
pub struct EqualTemperament;

impl Tuning for EqualTemperament {
	fn get_frequency(&self, note: f32) -> f32 {
		const A4: f32 = 440.0;
		const A4_MIDI: f32 = 57.0;

		let semitones = (note - A4_MIDI) / 12.0;
		A4 * 2.0f32.powf(semitones)
	}
}

/// Reference frequency for concert A4.
pub const A4_FREQ: f32 = 440.0;
/// MIDI note number of concert A4.
pub const A4_MIDI: f32 = 57.0;
/// MIDI note number of middle C (C4).
///
/// Consistent with [`A4_MIDI`]: in this library A4 is MIDI 57, so C4 is MIDI 48.
pub const C4_MIDI: f32 = 48.0;
/// Frequency of middle C (C4), matching A4 = 440 Hz in 12-EDO.
pub const C4_FREQ: f32 = 261.625_58;

/// Convert a MIDI note number to a frequency in Hz using an arbitrary scale. The
/// scale is indexed by pitch class (relative to C), so scale[0] must be 1.0
/// (the root / C) and the remaining entries are frequency ratios to the root
/// within the octave. Notes outside 0..scale.len() map across octaves.
fn scale_frequency(note: f32, scale: &[f32]) -> f32 {
	if scale.is_empty() {
		return 0.0;
	}

	let n = scale.len() as f32;
	// Rounded so floating-point note numbers snap to the nearest scale degree.
	let steps = (note - C4_MIDI).round();
	let octave = (steps / n).floor();
	let degree = (steps as i32).rem_euclid(scale.len() as i32) as usize;

	C4_FREQ * scale[degree] * 2.0f32.powf(octave)
}

/// An N-note equal division of the octave (N-EDO).
///
/// NEdoTuning::<12> is identical to EqualTemperament; 19, 24, 31 etc.
/// give the corresponding microtonal equal temperaments.
pub struct NEdoTuning<const N: u32>;

impl<const N: u32> Tuning for NEdoTuning<N> {
	fn get_frequency(&self, note: f32) -> f32 {
		let steps_per_octave = N as f32;
		A4_FREQ * 2.0f32.powf((note - A4_MIDI) / steps_per_octave)
	}
}

/// The 12-note five-limit just intonation scale (pure / just tuning).
///
/// All intervals are small integer ratios so chords beat minimally, but the
/// scale has unequal steps and can sound out of tune away from the tonic.
pub struct JustIntonation;

impl Tuning for JustIntonation {
	fn get_frequency(&self, note: f32) -> f32 {
		const JUST_RATIOS: [f32; 12] = [
			1.000000, 1.066667, 1.125, 1.2, 1.25, 1.333333, 1.406_25, 1.5, 1.6, 1.666667, 1.777778,
			1.875,
		];
		scale_frequency(note, &JUST_RATIOS)
	}
}

/// The Pythagorean tuning (3-limit), generated by perfect fifths of ratio 3/2.
///
/// Used historically for plainchant and early polyphony. The octave and fifths
/// are pure but the thirds are sharp and noticeably impure compared to just tuning.
pub struct PythagoreanTuning;

impl Tuning for PythagoreanTuning {
	fn get_frequency(&self, note: f32) -> f32 {
		const PYTHAGOREAN_RATIOS: [f32; 12] = [
			1.000000, 1.067871, 1.125, 1.201355, 1.265625, 1.333333, 1.423828, 1.5, 1.601807,
			1.687_5, 1.802032, 1.898438,
		];
		scale_frequency(note, &PYTHAGOREAN_RATIOS)
	}
}

/// A tuning system defined by an arbitrary scale of frequency ratios.
///
/// This lets you build any fixed (non-EDO) scale as a preset. ratios should be
/// one octave of ratios relative to the root, with ratios[0] == 1.0 (C). For
/// example a major pentatonic scale:
///
/// ScaleTuning::<5>::new([1.0, 9.0/8.0, 5.0/4.0, 3.0/2.0, 5.0/3.0])
///
/// Custom ratios (e.g. an Arabic maqam, an Indian thaat, or a Bohlen-Pierce
/// tritave) can be supplied as any f32 values greater than 0.0.
pub struct ScaleTuning<const N: usize> {
	ratios: [f32; N],
}

impl<const N: usize> ScaleTuning<N> {
	/// Create a new scale tuning from the given per-octave ratios.
	pub const fn new(ratios: [f32; N]) -> Self {
		Self { ratios }
	}
}

impl<const N: usize> Tuning for ScaleTuning<N> {
	fn get_frequency(&self, note: f32) -> f32 {
		scale_frequency(note, &self.ratios)
	}
}

/// A major pentatonic scale preset built on top of ScaleTuning.
pub const PENTATONIC: ScaleTuning<5> =
	ScaleTuning::new([1.0, 9.0 / 8.0, 5.0 / 4.0, 3.0 / 2.0, 5.0 / 3.0]);

/// A minor pentatonic scale preset built on top of ScaleTuning.
pub const PENTATONIC_MINOR: ScaleTuning<5> =
	ScaleTuning::new([1.0, 6.0 / 5.0, 4.0 / 3.0, 3.0 / 2.0, 9.0 / 5.0]);
