"""Iterate the calibration: measure, correct, rebuild, measure again.

The first pass tried to correct the engine in one step, but a projected partial
carries the body and its neighbours as well as the mode itself, so the map from
"mode level" to "measured level" is not one to one. This closes the loop with a
damped multiplicative update, which converges for a monotone map even when the
gain is not exactly one.
"""

import json
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import t60_map as tm
from calibrate_same import measure

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
LIBRARY = os.path.abspath(os.path.join(ROOT, '..', 'refer', 'sample', 'The Gentleman'))
MODES = os.path.join(ROOT, 'target', 'wav', 'gentleman-model', 'modes.json')
TABLE = os.path.join(ROOT, 'i_am_string', 'src', 'piano_calibration.rs')
OUT = os.path.join(ROOT, 'target', 'wav', 'loop')

HEAD = '''//! The piano, measured against The Gentleman at the same frequencies.
//!
//! Generated by tools/loop_calibration.py. Rows are
//! (frequency, gain, prompt T60, tail T60); a mode takes the row nearest it in
//! frequency.

/// One measured partial.
#[derive(Clone, Copy, Debug)]
pub struct Mode {
	/// Where the partial sits, in hertz.
	pub frequency: f32,
	/// Multiplier on the level of the mode that lands on it.
	pub gain: f32,
	/// T60 of the prompt decay, in seconds.
	pub prompt: f32,
	/// T60 of the tail, in seconds.
	pub tail: f32,
}

/// The rows for one note, empty when the note was not measured.
pub fn modes(note: u8) -> &'static [Mode] {
	match note {
'''


def write_table(state):
    lines = []
    for note in sorted(state):
        cells = ', '.join(
            'Mode { frequency: %.1f, gain: %.3f, prompt: %.3f, tail: %.3f }' % tuple(row)
            for row in state[note])
        lines.append('\t\t%d => &[%s],' % (note, cells))
    text = HEAD + '\n'.join(lines) + '\n\t\t_ => &[],\n\t}\n}\n'
    open(TABLE, 'w').write(text)


def render(directory, notes):
    exe = os.path.join(ROOT, 'target', 'release', 'examples', 'probe_piano.exe')
    subprocess.run([exe, directory, '3'] + [str(note) for note in notes],
                   cwd=ROOT, check=True, stdout=subprocess.DEVNULL)


def build():
    subprocess.run(['cargo', 'build', '--release', '-p', 'i_am_string',
                    '--example', 'probe_piano'], cwd=ROOT, check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def initial(library):
    state = {}
    for entry in library:
        rate, target = tm.load(os.path.join(LIBRARY, entry['file']))
        f0 = 440.0 * 2.0 ** ((entry['note'] - 69) / 12.0)
        rows = []
        for mode in entry['modes']:
            got = measure(target, rate, mode['f'], f0)
            if got is None:
                continue
            rows.append([mode['f'], 1.0, got['prompt'], got['tail']])
        if len(rows) >= 3:
            state[entry['note']] = rows
    return state


def compare(state, directory):
    ratios = []
    decays = []
    for entry in json.load(open(MODES)):
        note = entry['note']
        if note not in state:
            continue
        rate, engine = tm.load(os.path.join(directory, 'piano-%03d.wav' % note))
        _, target = tm.load(os.path.join(LIBRARY, entry['file']))
        f0 = 440.0 * 2.0 ** ((note - 69) / 12.0)
        rows = []
        for row in state[note]:
            a = measure(target, rate, row[0], f0)
            b = measure(engine, rate, row[0], f0)
            if a and b:
                rows.append((row, a, b))
        if len(rows) < 3:
            continue
        pk_a = max(r[1]['amp'] for r in rows)
        pk_b = max(r[2]['amp'] for r in rows)
        for row, a, b in rows:
            ratio = (a['amp'] / pk_a) / (b['amp'] / pk_b)
            decay = a['tail'] / b['tail']
            ratios.append(np.log(ratio))
            decays.append(np.log(decay))
            rate_log = np.log(ratio) * 0.5
            row[1] = float(np.clip(row[1] * np.exp(rate_log), 0.1, 8.0))
            row[2] = float(np.clip(row[2] * (a['prompt'] / b['prompt']) ** 0.5, 0.03, 2.0))
            row[3] = float(np.clip(row[3] * (a['tail'] / b['tail']) ** 0.5, 0.05, 30.0))
    return ratios, decays


def main():
    library = json.load(open(MODES))
    state = initial(library)
    notes = sorted(state)
    os.makedirs(OUT, exist_ok=True)
    for round_index in range(4):
        write_table(state)
        build()
        directory = os.path.join(OUT, 'round%d' % round_index)
        render(directory, notes)
        ratios, decays = compare(state, directory)
        print('round %d: before correction  gain 10-90%% %.2f..%.2f   tail %.2f..%.2f' % (
            round_index,
            float(np.exp(np.percentile(ratios, 10))), float(np.exp(np.percentile(ratios, 90))),
            float(np.exp(np.percentile(decays, 10))),
            float(np.exp(np.percentile(decays, 90)))), flush=True)
    write_table(state)
    build()
    print('table written', flush=True)


if __name__ == '__main__':
    main()