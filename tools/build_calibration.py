"""Measure the engine against The Gentleman and emit a calibration table.

The table is per note and per harmonic order: how much louder or quieter the
mode should be, and how fast it should decay. The two passes are the engine as
it stands, and the library.
"""

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import model_gentleman as mg
import t60_map as tm

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENGINE = os.path.join(ROOT, 'target', 'wav', 'engine-cal')
OUT = os.path.join(ROOT, 'i_am_string', 'src', 'piano_calibration.rs')


def strongest(modes):
    out = {}
    for mode in modes:
        key = int(round(mode['k']))
        if key < 1:
            continue
        strength = mode.get('amp', mode.get('prompt_amp', 0.0) + mode.get('tail_amp', 0.0))
        if key not in out or strength > out[key][1]:
            out[key] = (mode, strength)
    return {key: value[0] for key, value in out.items()}

def main():
    library = json.load(open(os.path.join(ROOT, 'target', 'wav', 'gentleman-model', 'modes.json')))
    table = []
    for entry in library:
        note = entry['note']
        rate, x = tm.load(os.path.join(ENGINE, 'piano-%03d.wav' % note))
        f0 = 440.0 * 2.0 ** ((note - 69) / 12.0)
        engine = strongest(mg.detect_modes(x, rate, f0))
        target = strongest(entry['modes'])
        common = sorted(set(engine) & set(target))
        if not common:
            print('note %d: nothing in common' % note)
            continue
        def level(mode):
            return mode.get('amp', mode.get('prompt_amp', 0.0) + mode.get('tail_amp', 0.0))
        gains = np.array([level(target[k]) / max(level(engine[k]), 1e-9) for k in common])
        gains = np.clip(gains, 0.3, 3.0)
        if 1 in common:
            gains = gains / gains[common.index(1)]
        rows = []
        for k, gain in zip(common, gains):
            mode = target[k]
            rows.append((k, float(gain), float(mode['prompt_t60']), float(mode['tail_t60'])))
        table.append((note, rows))
        print('note %3d  common %2d  gain %5.2f..%5.2f  t60 %5.2f..%5.2f' % (
            note, len(common), float(gains.min()), float(gains.max()),
            min(row[2] for row in rows), max(row[2] for row in rows)))
    lines = ['//! The piano\'s modes, measured against The Gentleman.',
             '//!',
             '//! Generated by tools/build_calibration.py. Each row is a note and',
             '//! then its modes as (order, gain, prompt T60, tail T60).',
             '',
             '/// One calibrated mode.',
             '#[derive(Clone, Copy, Debug)]',
             'pub struct Mode {'
             '\t/// Harmonic order the mode belongs to.',
             '\tpub order: f32,',
             '\t/// Multiplier on the mode\'s level, relative to the note.',
             '\tpub gain: f32,',
             '\t/// T60 of the prompt decay, in seconds.',
             '\tpub prompt: f32,',
             '\t/// T60 of the tail, in seconds.',
             '\tpub tail: f32,',
             '}',
             '',
             '/// The calibrated modes for one note, empty when the note is not calibrated.',
             'pub fn modes(note: u8) -> &\'static [Mode] {',
             '\tmatch note {']
    for note, rows in table:
        body = ', '.join('Mode { order: %.1f, gain: %.4f, prompt: %.3f, tail: %.3f }' % row
                          for row in rows)
        lines.append('\t\t%d => &[%s],' % (note, body))
    lines += ['\t\t_ => &[],', '\t}', '}', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()