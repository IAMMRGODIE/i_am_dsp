"""Measure the engine against The Gentleman and emit a calibration table.

Both signals are projected onto the sample's own mode frequencies with the
same kernel, so what comes out is a per-frequency correction rather than a
per-order one: how much of that partial the engine has, and how fast it should
decay. The engine matches rows by frequency, not by harmonic order.
"""

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import t60_map as tm
from calibrate_same import measure

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
ENGINE = os.path.join(ROOT, 'target', 'wav', 'engine-cal')
LIBRARY = os.path.abspath(os.path.join(ROOT, '..', 'refer', 'sample', 'The Gentleman'))
MODES = os.path.join(ROOT, 'target', 'wav', 'gentleman-model', 'modes.json')
OUT = os.path.join(ROOT, 'i_am_string', 'src', 'piano_calibration.rs')


def main():
    library = json.load(open(MODES))
    notes = []
    for entry in library:
        note = entry['note']
        path = os.path.join(ENGINE, 'piano-%03d.wav' % note)
        if not os.path.exists(path):
            continue
        rate, engine = tm.load(path)
        _, target = tm.load(os.path.join(LIBRARY, entry['file']))
        f0 = 440.0 * 2.0 ** ((note - 69) / 12.0)
        rows = []
        for mode in entry['modes']:
            a = measure(target, rate, mode['f'], f0)
            b = measure(engine, rate, mode['f'], f0)
            if a is None or b is None:
                continue
            rows.append((mode['f'], a, b))
        if len(rows) < 3:
            continue
        target_peak = max(row[1]['amp'] for row in rows)
        engine_peak = max(row[2]['amp'] for row in rows)
        gains = np.array([(row[1]['amp'] / target_peak) / (row[2]['amp'] / engine_peak)
                          for row in rows])
        gains = np.clip(gains, 0.2, 5.0)
        gains = gains / float(np.exp(np.mean(np.log(gains))))
        table = [(row[0], float(gain), float(row[1]['prompt']), float(row[1]['tail']))
                 for row, gain in zip(rows, gains)]
        notes.append((note, table))
        print('note %3d  rows %2d  gain %4.2f..%4.2f  t60 %4.2f..%4.2f' % (
            note, len(table), gains.min(), gains.max(),
            min(row[2] for row in table), max(row[2] for row in table)))

    head = '''//! The piano, measured against The Gentleman at the same frequencies.
//!
//! Generated by tools/build_calibration.py. Rows are
//! (frequency, gain, prompt T60, tail T60); a mode takes the row nearest it in
//! frequency, so the table corrects partials rather than harmonic orders.

/// One measured partial.
#[derive(Clone, Copy, Debug)]
pub struct Mode {
	/// Where the partial sits, in hertz.
	pub frequency: f32,
	/// Multiplier on the level of the mode that lands on it.
	pub gain: f32,
	/// T60 of the prompt decay, in seconds.
	pub prompt: f32,
	/// T60 of the tail, in seconds.
	pub tail: f32,
}

/// The rows for one note, empty when the note was not measured.
pub fn modes(note: u8) -> &'static [Mode] {
	match note {
'''
    body = []
    for note, table in notes:
        cells = ', '.join(
            'Mode { frequency: %.1f, gain: %.3f, prompt: %.3f, tail: %.3f }' % row
            for row in table)
        body.append('		%d => &[%s],' % (note, cells))
    text = head + '\n'.join(body) + '\n\t\t_ => &[],\n\t}\n}\n'
    open(OUT, 'w').write(text)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
